// Every translated text (docs/plans/translations.md): the app's own words
// (scope "interface", no business) and each business's texts (scope
// "business"), one row per text and language, with the English it is made
// from. Google fills them in the background (lib/translations/queue.ts).
export const translationEntries = sqliteTable(
  "translation_entries",
  {
    id: id(),
    scope: text({ enum: TRANSLATION_SCOPES }).notNull(),
    businessId: text().references(() => businesses.id, { onDelete: "cascade" }),
    // Interface: the page or part ("dashboard.bookings"). Business: the kind
    // of text ("service.name").
    module: text().notNull(),
    // Interface: the word's key. Business: `${entityId}:${field}`.
    key: text().notNull(),
    language: text().notNull(),
    sourceText: text().notNull(),
    sourceHash: text().notNull(),
    // What the page shows (lib/translations/rules.ts `isShown`); null while
    // there is none yet.
    text: text(),
    // Google's latest translation and the English it came from, for "Reset
    // to Google".
    machineText: text(),
    machineSourceHash: text(),
    status: text({ enum: TRANSLATION_STATUSES }).notNull(),
    // Who made `text`.
    origin: text({ enum: TRANSLATION_ORIGINS }),
    // Failed tries since the last success, the next try, and the last error.
    attempts: integer().notNull().default(0),
    nextAttemptAt: text(),
    lastError: text(),
    ...timestamps(),
  },
  (table) => [
    uniqueIndex("translation_entries_scope_key_language_idx").on(
      table.scope,
      table.key,
      table.language
    ),
    index("translation_entries_queue_idx").on(
      table.status,
      table.nextAttemptAt
    ),
    index("translation_entries_business_idx").on(
      table.businessId,
      table.language
    ),
    index("translation_entries_memory_idx").on(
      table.language,
      table.sourceHash
    ),
  ]
)


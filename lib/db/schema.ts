// From now on bookings.durationMinutes and bookings.priceMinor are the
// TOTALS (service + add-ons; priceMinor null only when the service has no
// price and no add-on has one). The add-ons are in booking_addons.
export const bookings = sqliteTable(
  "bookings",
  {
    id: id(),
    businessId: text()
      .notNull()
      .references(() => businesses.id, { onDelete: "cascade" }),
    serviceId: text().references(() => services.id, { onDelete: "set null" }),
    teamMemberId: text().references(() => teamMembers.id, {
      onDelete: "set null",
    }),
    serviceName: text().notNull(),
    teamMemberName: text(),
    durationMinutes: integer().notNull(),
    priceMinor: integer(),
    currency: text().notNull(),
    startAt: text().notNull(),
    endAt: text().notNull(),
    customerName: text().notNull(),
    customerPhone: text(),
    // customerKey(customerPhone, customerName) from lib/customer-key.ts,
    // set on every new booking. Null only on bookings made before it
    // existed, until `npm run customers:backfill` fills them.
    customerKey: text(),
    // The account the booking belongs to on My bookings: the signed-in
    // person who booked it, or the one who logged in from "Manage your
    // booking" (claimToken). Null for owner-made bookings and bookings
    // nobody claimed; those still show by the account's verified phone.
    customerUserId: text().references(() => user.id, { onDelete: "set null" }),
    // A booking made signed out: the SHA-256 of a one-time secret kept in
    // the booker's tab, so only that tab can join it to an account.
    // Cleared once claimed.
    claimTokenHash: text(),
    source: text().notNull().default("online"),
    note: text(),
    status: text().notNull().default("confirmed"),
    // Why the owner cancelled it (CANCEL_REASONS in lib/booking-rules.ts);
    // null when no reason was picked.
    cancelReason: text({ enum: CANCEL_REASONS }),
    // The customer agreed to booking messages on WhatsApp (Meta requires
    // opt-in), and the language they booked in.
    whatsappOptIn: integer({ mode: "boolean" }).notNull().default(false),
    language: text({ enum: PAGE_LANGUAGES }),
    // How many times the owner moved it: each move gets its own "Booking
    // changed" message and reminders (D5).
    moves: integer().notNull().default(0),
    // When the customer agreed to the business's policies in the booking
    // flow; null when it had none to agree to, or for owner-made bookings.
    policiesAcceptedAt: text(),
    // Paying outside the app (lib/payment-rules.ts), all null on a booking
    // made where the business offers no such way, or made by the owner.
    // paymentChoice: now (by paymentMethod) or later (at the visit).
    // paymentMethod: the way as it was when they booked, so its
    // instructions stay what the customer saw.
    // paymentStatus: unpaid, reported (the customer says they paid) or
    // paid; only the business sets paid.
    paymentChoice: text({ enum: PAYMENT_CHOICES }),
    paymentMethod: text({ mode: "json" }).$type<PaymentMethodSnapshot>(),
    paymentStatus: text({ enum: PAYMENT_STATUSES }),
    paymentReference: text(),
    paymentReportedAt: text(),
    paymentPaidAt: text(),
    ...timestamps(),
  },
  (table) => [
    index("bookings_business_idx").on(table.businessId, table.startAt),
    index("bookings_customer_idx").on(
      table.businessId,
      table.customerKey,
      table.startAt
    ),
    index("bookings_customer_user_idx").on(
      table.customerUserId,
      table.startAt
    ),
  ]
)


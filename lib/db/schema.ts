function timestamps() {
  return {
    createdAt: text()
      .notNull()
      .$defaultFn(() => new Date().toISOString()),
    updatedAt: text()
      .notNull()
      .$defaultFn(() => new Date().toISOString())
      .$onUpdate(() => new Date().toISOString()),
  }
}

function id() {
  return text()
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID())
}

